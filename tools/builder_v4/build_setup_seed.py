"""EXPRESS setup-repo builder, seed half (spec v1.0.4 section 5 stages 1 to 3, section 7).

Validates File 1 and File 3 against the contract, derives the load plan, writes one RFC 4180
CSV static resource per step, the SEED_PLAN.json resource, the generic Batch Apex loader
and its tests, and the generated census, teardown and run scripts. Client-free: everything
client-specific arrives through the arguments.

Usage:
    python3 build_setup_seed.py --file1 F1.xlsx --file3 F3.xlsx --describe d.json \
        --client client.json --out <repo>/clients/<Code>

Exit 0 means every validation passed and every file was written.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import contract as C                     # noqa: E402
import apex_templates as A               # noqa: E402

NS = 'xmlns="http://soap.sforce.com/2006/04/metadata"'


def write(root, rel, text, written):
    path = os.path.join(root, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    written.append(rel)


def class_meta():
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n<ApexClass {NS}>\n'
            f'    <apiVersion>{C.API_VERSION}</apiVersion>\n    <status>Active</status>\n</ApexClass>\n')


def resource_meta(content_type, description):
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n<StaticResource {NS}>\n'
            f'    <cacheControl>Private</cacheControl>\n    <contentType>{content_type}</contentType>\n'
            f'    <description>{description}</description>\n</StaticResource>\n')


def apex_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def seed_shape(w1, obj):
    """The owner lineage field marks seeded rows, when every File 1 row of obj carries one."""
    t = w1.tabs[obj]
    f = C.owner_field(w1, obj)
    if f and C.OWNER_HEADER in t.headers and all(v != "" for v in t.values(C.OWNER_HEADER)):
        return f
    return None


def census_script(plan, client):
    rows = plan["census"]
    labels, queries, exp = [], [], []
    for r in rows:
        where = []
        if r.get("record_type"):
            where.append(f"RecordType.DeveloperName = '{r['record_type']}'")
        if r.get("filter"):
            where.append(r["filter"])
        q = f"SELECT COUNT() FROM {r['object']}" + (" WHERE " + " AND ".join(where) if where else "")
        labels.append(r["object"] + (f".{r['record_type']}" if r.get("record_type") else ""))
        queries.append(q)
        exp.append(str(r["expected"]))
    return f"""// EXPRESS seed census for {client['code']}. Generated by build_setup_seed.py from the plan;
// expected deltas are counted from File 1 (content md5 {plan['file1_content_md5']}), never typed.
// Anonymous Apex: paste the whole file, Execute. Logs at ERROR level; |ERROR| is not a failure.
// Pass 1: MODE='BEFORE'. Copy the one-line BEFORE= string it prints.
// Pass 2: paste that line over BEFORE below, set MODE='AFTER', run again.
String MODE = 'BEFORE';
String BEFORE = '';

List<String> K = new List<String>{{{', '.join(apex_str(x) for x in labels)}}};
List<Integer> EXP = new List<Integer>{{{', '.join(exp)}}};
List<String> Q = new List<String>{{
    {(','+chr(10)+'    ').join(apex_str(q) for q in queries)}}};

List<Integer> NOW = new List<Integer>();
for (Integer i = 0; i < K.size(); i++) {{
    try {{ NOW.add(Database.countQuery(Q[i])); }} catch (Exception e) {{ NOW.add(-1); }}
}}
if (MODE == 'BEFORE') {{
    List<String> v = new List<String>();
    for (Integer n : NOW) {{ v.add(String.valueOf(n < 0 ? 0 : n)); }}
    System.debug(LoggingLevel.ERROR, 'COPY THIS LINE:\\nString BEFORE = \\'' + String.join(v, ',') + '\\';');
    return;
}}
if (String.isBlank(BEFORE)) {{
    System.debug(LoggingLevel.ERROR, 'STOP: MODE is AFTER but BEFORE is empty. Paste the BEFORE line printed by pass 1, then run again.');
    return;
}}
List<String> b = BEFORE.split(',');
if (b.size() != K.size()) {{
    System.debug(LoggingLevel.ERROR, 'STOP: BEFORE has ' + b.size() + ' values, expected ' + K.size() + '. Copy the whole line.');
    return;
}}
Boolean ok = true;
System.debug(LoggingLevel.ERROR, 'OBJECT / BEFORE / AFTER / DELTA / EXPECTED / RESULT');
for (Integer i = 0; i < K.size(); i++) {{
    Integer bv = Integer.valueOf(b[i].trim());
    Integer d = NOW[i] - bv;
    String res = NOW[i] < 0 ? 'FAIL not countable' : (d == EXP[i] ? 'PASS' : 'FAIL off by ' + (d - EXP[i]));
    if (res != 'PASS') {{ ok = false; }}
    System.debug(LoggingLevel.ERROR, K[i] + ' / ' + bv + ' / ' + NOW[i] + ' / ' + d + ' / ' + EXP[i] + ' / ' + res);
}}
System.debug(LoggingLevel.ERROR, ok ? 'CENSUS PASS: every delta equals File 1.' : 'CENSUS FAIL: a Completed job is not proof of success.');
"""


def teardown_script(plan, w1, client):
    objs = []
    for s in reversed(plan["steps"]):
        if s["op"] != "insert":
            continue
        o = s["object"]
        where = ["CreatedById = :me"]
        if o in C.CENSUS_FILTERS:
            where.append(C.CENSUS_FILTERS[o])
        shape = seed_shape(w1, o)
        if shape:
            where.append(f"{shape} != null")
        objs.append((o, " AND ".join(where)))
    lines = ",\n    ".join(f"{apex_str(o)} => {apex_str(w)}" for o, w in objs)
    order = ", ".join(apex_str(o) for o, _ in objs)
    return f"""// EXPRESS teardown for {client['code']}. Generated by build_setup_seed.py from the plan.
// Scope: records the running user created, minus platform side-effect rows, and, where every
// seeded row carries one, the owner lineage field. Children first.
// MODE = 'REPORT' changes nothing. MODE = 'DELETE' deletes; rerun until every count is 0.
// VERIFY WITH scripts/census.apex, NOT WITH THIS SCRIPT'S OWN OUTPUT.
String MODE = 'REPORT';
Id me = UserInfo.getUserId();
List<String> SEED_ORDER = new List<String>{{{order}}};
Map<String, String> SCOPE_BY_OBJECT = new Map<String, String>{{
    {lines}
}};
Boolean doDelete = MODE == 'DELETE';
System.debug(LoggingLevel.ERROR, 'EXPRESS teardown, MODE = ' + MODE + (doDelete ? '  *** THIS RUN DELETES ***' : '  (nothing will change)'));
Boolean more = false;
for (String o : SEED_ORDER) {{
    String w = SCOPE_BY_OBJECT.get(o);
    Integer n = Database.countQuery('SELECT COUNT() FROM ' + o + ' WHERE ' + w);
    System.debug(LoggingLevel.ERROR, o + ': ' + n);
    if (!doDelete || n == 0) {{ continue; }}
    Integer room = Limits.getLimitDmlRows() - Limits.getDmlRows();
    if (room <= 0) {{ more = true; continue; }}
    List<SObject> doomed = Database.query('SELECT Id FROM ' + o + ' WHERE ' + w + ' LIMIT ' + Math.min(room, 9000));
    Database.delete(doomed, false);
    if (doomed.size() < n) {{ more = true; }}
}}
if (doDelete) {{
    System.debug(LoggingLevel.ERROR, more ? 'MORE ROWS REMAIN: run this script again.' : 'Delete pass done. Run again in REPORT mode; every count must be 0.');
}}
"""


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    for a in ("--file1", "--file3", "--describe", "--client", "--out"):
        ap.add_argument(a, required=True)
    args = ap.parse_args(argv)
    with open(args.client, encoding="utf-8") as fh:
        client = json.load(fh)
    d = C.load_describe(args.describe)
    try:
        w1 = C.load_file1(args.file1, d)
        auto = C.load_auto_spec(args.file3, w1, d)
        C.check_seed_against_v1(w1, auto)
        plan = C.build_plan(w1, d, batch_size=int(client.get("batch_size", C.DEFAULT_BATCH_SIZE)))
    except C.ContractError as e:
        print("VALIDATION FAILED", file=sys.stderr)
        for x in e.errors:
            print("  " + x, file=sys.stderr)
        return 2
    out = os.path.abspath(args.out)
    fa = "force-app/main/default"
    written = []
    texts = C.resource_texts(plan)
    for name, text in texts:
        write(out, f"{fa}/staticresources/{name}.csv", text, written)
        write(out, f"{fa}/staticresources/{name}.resource-meta.xml",
              resource_meta("text/csv", f"EXPRESS seed data for {client['code']}, generated"), written)
    pub = C.public_plan(plan)
    pub["client"] = client["code"]
    write(out, f"{fa}/staticresources/SEED_PLAN.json", json.dumps(pub, indent=1, sort_keys=True) + "\n", written)
    write(out, f"{fa}/staticresources/SEED_PLAN.resource-meta.xml",
          resource_meta("application/json", f"EXPRESS seed plan for {client['code']}, generated"), written)
    for cls, src in (("ExpressCsv", A.EXPRESS_CSV), ("ExpressSeed", A.EXPRESS_SEED),
                     ("ExpressSeedBatch", A.EXPRESS_SEED_BATCH), ("ExpressSeedTest", A.EXPRESS_SEED_TEST)):
        write(out, f"{fa}/classes/{cls}.cls", src, written)
        write(out, f"{fa}/classes/{cls}.cls-meta.xml", class_meta(), written)
    write(out, "scripts/census.apex", census_script(plan, client), written)
    write(out, "scripts/reset-data.apex", teardown_script(plan, w1, client), written)
    write(out, "scripts/check-setup.apex",
          "// Prechecks only. Prints SETUP OK, or throws SETUP INCOMPLETE / ALREADY SEEDED naming the first gap.\n"
          "ExpressSeed.checkSetup();\n", written)
    write(out, "scripts/reset-bypass.apex",
          "// Recovery only: clear the seed bypass if a run died before its last step finished.\n"
          "ExpressSeed.setBypass(false);\n"
          "System.debug(LoggingLevel.ERROR, 'BYPASS NOW ' + Migration_Settings__c.getOrgDefaults().Bypass_Automation__c);\n",
          written)
    write(out, "scripts/run-seed.apex",
          "// Starts the seed: prechecks, bypass on, one Batch job per plan step.\n"
          "// The verdict line (SEED PASS / SEED FAIL) arrives by email and in Seed_Step_Result__c.\n"
          "ExpressSeed.run();\n", written)
    total = sum(s["rows"] for s in plan["steps"])
    print(f"VALIDATION OK: 0 errors. File 1 bytes md5 {w1.md5}, content md5 {plan['file1_content_md5']}")
    print(f"PLAN: {len(plan['steps'])} steps, {total} row operations")
    for s in plan["steps"]:
        print(f"  {s['name']:<40} rows {s['rows']:>6}  {','.join(s['resources'])}")
    print(f"WROTE {len(written)} files under {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
